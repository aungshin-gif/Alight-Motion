/**
 * Helper to get a translation value safely with fallback to Indonesian ('id')
 */
function t(langCode, path, ...args) {
    const lang = translations[langCode] ? langCode : 'id';
    const keys = path.split('.');
    
    let value = translations[lang];
    for (const key of keys) {
        if (value && value[key] !== undefined) {
            value = value[key];
        } else {
            value = undefined;
            break;
        }
    }

    if (value === undefined && lang !== 'id') {
        value = translations['id'];
        for (const key of keys) {
            if (value && value[key] !== undefined) {
                value = value[key];
            } else {
                value = undefined;
                break;
            }
        }
    }

    if (typeof value === 'function') {
        return value(...args);
    }

    return value || '';
}

function getSupportedLanguages() {
    return SUPPORTED_LANGUAGES;
}

function getLanguageMeta(langCode) {
    const lang = translations[langCode] ? langCode : 'id';
    return translations[lang].meta;
}

